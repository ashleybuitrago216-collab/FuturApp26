export function getVisibleHelpArticles(role) {
  return helpArticles.filter(article => article.roles.includes("todos") || article.roles.includes(role));
}

export function getHelpCategories(articles) {
  return ["Todas", ...Array.from(new Set(articles.map(article => article.category))).sort((a, b) => a.localeCompare(b))];
}
